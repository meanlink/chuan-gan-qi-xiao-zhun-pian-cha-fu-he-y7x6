from enum import Enum
class Role(str, Enum):
    admin = 'admin'
    analyst = 'analyst'
    viewer = 'viewer'
class JobStatus(str, Enum):
    queued = 'queued'
    running = 'running'
    completed = 'completed'
    failed = 'failed'
class HoldbackStatus(str, Enum):
    sealed = 'sealed'
    in_use = 'in_use'
    consumed = 'consumed'
class CaseStatus(str, Enum):
    open = 'open'
    locked = 'locked'
    queued = 'queued'
    running = 'running'
    completed = 'completed'
    failed = 'failed'
class Verdict(str, Enum):
    released = 'released'
    rejected = 'rejected'
